//! Generates the Omniglot bindings of `chips/esp32-c3-ble-omniglot` from its
//! sandbox's `sandbox.h`.
//!
//! The bindings are checked in, so that building the chip crate does not
//! need libclang. Run this after changing `sandbox.h` or
//! `sandbox.omniglot.toml`:
//!
//! ```shell
//! make -C boards/esp32-c3-devkitM-1 ble-omniglot-bindings
//! ```

use std::path::PathBuf;
use std::process::Command;

const HEADER: &str = "\
// Licensed under the Apache License, Version 2.0 or the MIT License.
// SPDX-License-Identifier: Apache-2.0 OR MIT
// Copyright Tock Contributors 2026.

// Generated by `tools/build/ble-omniglot-bindgen` from `sandbox/sandbox.h`.
// Do not edit.

";

fn main() {
    let crate_dir =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../chips/esp32-c3-ble-omniglot");
    let crate_dir = crate_dir.canonicalize().expect("chip crate not found");
    let sandbox = crate_dir.join("sandbox");

    let bindings = bindgen::Builder::default()
        .header(sandbox.join("sandbox.h").to_str().unwrap())
        .clang_args([
            "--target=riscv32-unknown-none-elf",
            "-march=rv32imc",
            "-mabi=ilp32",
            "-ffreestanding",
        ])
        .omniglot_configuration_file(Some(sandbox.join("sandbox.omniglot.toml")))
        .allowlist_function("sandbox_.*")
        .allowlist_var("SANDBOX_.*")
        .use_core()
        .formatter(bindgen::Formatter::None)
        .generate()
        .expect("Unable to generate Omniglot bindings");

    let out = crate_dir.join("src/bindings.rs");
    std::fs::write(&out, format!("{HEADER}{bindings}")).expect("Couldn't write bindings");

    let status = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(&out)
        .status()
        .expect("Couldn't run rustfmt");
    assert!(status.success(), "rustfmt failed");
    println!("Wrote {}", out.display());
}
